@app.get("/api/download-agent")
def download_agent(
    request: Request,
    agent_type: Literal["windows", "linux", "python"] = Query("windows", alias="type"),
    portal_url: str = "",
    company: str = "",
    site: str = "",
    department: str = "",
    device_type: str = "",
    custom_name: str = Query("", max_length=200),
):
    portal_url = portal_url.strip().rstrip("/")
    if not portal_url:
        portal_url = default_portal_url(request)
    if not PORTAL_URL_RE.match(portal_url):
        raise HTTPException(status_code=422, detail="Portal URL must look like http://192.168.1.20:8000")

    config = {
        "portal_url": portal_url,
        "company": clean_label(company),
        "site": clean_label(site),
        "department": clean_label(department),
        "device_type": clean_label(device_type),
        "custom_name": clean_label(custom_name, 63),
    }
    company_part = filename_part(config["company"], "Agent")

    if agent_type == "windows":
        exe_path = build_windows_agent(config)
        return FileResponse(exe_path, media_type="application/octet-stream",
                            filename=f"ITPortalAgent_{company_part}.exe")

    if agent_type == "linux":
        content, filename, media_type = render_linux_agent(config), f"ITPortalAgent_{company_part}.sh", "text/x-shellscript"
    else:
        content, filename, media_type = render_python_agent(config), f"ITPortalAgent_{company_part}.py", "text/x-python"
    return Response(content=content.encode("utf-8"), media_type=media_type,
                    headers={"Content-Disposition": f'attachment; filename="{filename}"'})
