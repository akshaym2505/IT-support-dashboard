@app.put("/api/tickets/{ticket_id}/notes/{note_id}")
def update_ticket_note(ticket_id: str, note_id: int, note: NoteUpdate):
    changes = {}
    if note.note_type is not None:
        changes["note_type"] = note.note_type
    if note.text is not None:
        text = note.text.strip()
        if not text:
            raise HTTPException(status_code=422, detail="Note text cannot be empty.")
        changes["text"] = text
    if note.time_spent_minutes is not None:
        changes["time_spent_minutes"] = note.time_spent_minutes
    if not changes:
        raise HTTPException(status_code=400, detail="Nothing to update.")
    changes["updated_at"] = utc_now()

    set_clause = ", ".join(f"{column} = ?" for column in changes)
    with db() as conn:
        cursor = conn.execute(f"UPDATE ticket_notes SET {set_clause} WHERE id = ? AND ticket_id = ?",
                              (*changes.values(), note_id, ticket_id))
        if cursor.rowcount == 0:
            raise HTTPException(status_code=404, detail="Note not found.")
        updated = fetch_note(conn, ticket_id, note_id)
    return updated


