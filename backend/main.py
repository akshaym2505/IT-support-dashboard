@app.get("/api/dashboard-stats")
def get_stats():
    with db() as conn:
        rows = conn.execute("SELECT status, priority FROM tickets").fetchall()

    stats = {'total': len(rows), 'open': 0, 'pending': 0, 'resolved': 0, 'closed': 0, 'critical': 0}

    for row in rows:
        status, priority = (row["status"] or "").lower(), (row["priority"] or "").lower()
        if status in stats:
            stats[status] += 1
        # "Critical" = urgent tickets that still need work
        if priority in ['critical', 'high'] and status not in ('resolved', 'closed'):
            stats['critical'] += 1

    return stats


@app.get("/api/tickets")
def get_tickets():
    with db() as conn:
        rows = conn.execute('''SELECT t.rowid AS _rowid, t.*,
                                   (SELECT COUNT(*) FROM ticket_notes n WHERE n.ticket_id = t.id) AS notes_count
                               FROM tickets t''').fetchall()

    tickets_list = [dict(row) for row in rows]
    # Newest first. createdAt is text in two formats, so it can't be sorted in SQL.
    tickets_list.sort(key=lambda t: (created_sort_key(t["createdAt"]), t["_rowid"]), reverse=True)
    for ticket in tickets_list:
        del ticket["_rowid"]
    return tickets_list


@app.get("/api/tickets/{ticket_id}")
def get_ticket(ticket_id: str):
    with db() as conn:
        ticket = fetch_ticket(conn, ticket_id)
    if not ticket:
        raise HTTPException(status_code=404, detail=f"Ticket {ticket_id} not found.")
    return ticket


@app.post("/api/tickets", status_code=201)
def create_ticket(ticket: Ticket):
    subject, requester, email, description = (ticket.subject.strip(), ticket.requester.strip(),
                                              ticket.email.strip(), ticket.description.strip())
    if not (subject and requester and email and description):
        raise HTTPException(status_code=422, detail="Subject, requester, email and description are required.")
    category = require_choice(ticket.category, TICKET_CATEGORIES, "category")
    priority = require_choice(ticket.priority, TICKET_PRIORITIES, "priority")
    status = require_choice(ticket.status, TICKET_STATUSES, "status")
    assigned = (ticket.assigned or "").strip() or "Unassigned"

    try:
        with db() as conn:
            # take the write lock first so two requests can't pick the same next id
            conn.execute("BEGIN IMMEDIATE")
            ticket_id = (ticket.id or "").strip() or next_ticket_id(conn)
            conn.execute('''INSERT INTO tickets
                         (id, subject, requester, email, category, priority, status, assigned, description, createdAt)
                         VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)''',
                         (ticket_id, subject, requester, email, category, priority, status, assigned,
                          description, ticket.createdAt or utc_now()))
    except sqlite3.IntegrityError:
        raise HTTPException(status_code=400, detail="Ticket ID already exists.")
    return {"message": "Ticket created successfully!", "id": ticket_id}


@app.put("/api/tickets/{ticket_id}")
def update_ticket(ticket_id: str, ticket_update: TicketUpdate):
    changes = {}
    if ticket_update.status is not None:
        changes["status"] = require_choice(ticket_update.status, TICKET_STATUSES, "status")
    if ticket_update.priority is not None:
        changes["priority"] = require_choice(ticket_update.priority, TICKET_PRIORITIES, "priority")
    if ticket_update.category is not None:
        changes["category"] = require_choice(ticket_update.category, TICKET_CATEGORIES, "category")
    if ticket_update.assigned is not None:
        assigned = ticket_update.assigned.strip()[:80]
        changes["assigned"] = assigned or "Unassigned"
    if not changes:
        raise HTTPException(status_code=400, detail="Nothing to update.")

    # column names come from the fixed keys above, never from user input
    set_clause = ", ".join(f"{column} = ?" for column in changes)
    with db() as conn:
        cursor = conn.execute(f"UPDATE tickets SET {set_clause} WHERE id = ?", (*changes.values(), ticket_id))
        if cursor.rowcount == 0:
            raise HTTPException(status_code=404, detail=f"Ticket {ticket_id} not found.")
        ticket = fetch_ticket(conn, ticket_id)
    return {"message": "Ticket updated successfully", "ticket": ticket}


