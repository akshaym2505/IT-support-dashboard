@app.post("/api/remote-machines/register")
def register_remote_machine(machine: RemoteMachine, response: Response):
    """Used by the installers: creates the machine, or refreshes it if it re-registers."""
    with db() as conn:
        existed = conn.execute("SELECT 1 FROM remote_machines WHERE machine_id = ?",
                               (machine.machine_id,)).fetchone() is not None
        conn.execute('''INSERT INTO remote_machines
                     (machine_id, hostname, ip_address, os_type, user, status, remote_url,
                      company, site, department, device_type, last_seen)
                     VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                     ON CONFLICT(machine_id) DO UPDATE SET
                        hostname = excluded.hostname, ip_address = excluded.ip_address,
                        os_type = excluded.os_type, user = excluded.user, status = excluded.status,
                        company = COALESCE(NULLIF(excluded.company, ''), remote_machines.company),
                        site = COALESCE(NULLIF(excluded.site, ''), remote_machines.site),
                        department = COALESCE(NULLIF(excluded.department, ''), remote_machines.department),
                        device_type = COALESCE(NULLIF(excluded.device_type, ''), remote_machines.device_type),
                        last_seen = excluded.last_seen''',
                     (machine.machine_id, machine.hostname, machine.ip_address,
                      machine.os_type, machine.user, machine.status, machine.remote_url,
                      machine.company, machine.site, machine.department, machine.device_type, utc_now()))
    response.status_code = 200 if existed else 201
    return {"message": "Machine registration updated" if existed else "Machine registered",
            "machine_id": machine.machine_id, "created": not existed}


