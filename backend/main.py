PORTAL_URL_RE = re.compile(r"^https?://[A-Za-z0-9.\-]+(:\d{1,5})?/?$")
CONTROL_CHARS_RE = re.compile(r"[\x00-\x1f\x7f]")


def detect_lan_ip():
    """The IPv4 address other machines on the network can reach this server on."""
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as probe:
            probe.connect(("10.255.255.255", 1))  # UDP connect sends no packets
            return probe.getsockname()[0]
    except OSError:
        return "127.0.0.1"


def default_portal_url(request):
    """This server's address as other machines should see it (LAN IP instead of localhost)."""
    scheme = request.url.scheme
    port = request.url.port
    default_port = 443 if scheme == "https" else 80
    suffix = "" if port in (None, default_port) else f":{port}"
    return f"{scheme}://{detect_lan_ip()}{suffix}"


def find_csc():
    """The C# compiler that ships with the .NET Framework 4.x on every Windows PC."""
    windir = os.environ.get("WINDIR", r"C:\Windows")
    for framework in ("Framework64", "Framework"):
        path = os.path.join(windir, "Microsoft.NET", framework, "v4.0.30319", "csc.exe")
        if os.path.isfile(path):
            return path
    return shutil.which("csc")


def clean_label(value, max_length=80):
    return CONTROL_CHARS_RE.sub("", (value or "").strip())[:max_length]


def filename_part(value, fallback):
    cleaned = re.sub(r"[^A-Za-z0-9_-]+", "_", value or "").strip("_")[:40]
    return cleaned or fallback


def cs_string(value):
    """Encode text as a C# string literal (anything outside printable ASCII is \\u-escaped)."""
    out = ['"']
    for ch in value:
        code = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif 32 <= code < 127:
            out.append(ch)
        elif code > 0xFFFF:
            out.append("\\U%08x" % code)
        else:
            out.append("\\u%04x" % code)
    out.append('"')
    return "".join(out)


def sh_string(value):
    return "'" + value.replace("'", "'\\''") + "'"


def render_agent_config(config):
    lines = ["// Generated by the IT Support Portal backend for one installer download.",
             "internal static class AgentConfig",
             "{"]
    for name, key in (("PortalUrl", "portal_url"), ("Company", "company"), ("Site", "site"),
                      ("Department", "department"), ("DeviceType", "device_type"),
                      ("CustomName", "custom_name")):
        lines.append(f"    public const string {name} = {cs_string(config[key])};")
    lines.append("}")
    return "\n".join(lines) + "\n"


AGENT_BUILD_LOCK = threading.Lock()


def prune_agent_builds(keep=20):
    builds = []
    for name in os.listdir(AGENT_BUILD_DIR):
        path = os.path.join(AGENT_BUILD_DIR, name)
        if name.endswith(".exe"):
            try:
                builds.append((os.path.getmtime(path), path))
            except OSError:
                pass
    builds.sort(reverse=True)
    for _, stale in builds[keep:]:
        try:
            os.remove(stale)
        except OSError:
            pass


def build_windows_agent(config):
    """Compile ITPortalAgent.cs with this download's settings; builds are cached."""
    with open(AGENT_SOURCE, "rb") as source_file:
        source = source_file.read()
    config_source = render_agent_config(config)
    digest = hashlib.sha256(source + config_source.encode("utf-8")).hexdigest()[:16]
    os.makedirs(AGENT_BUILD_DIR, exist_ok=True)
    output_path = os.path.join(AGENT_BUILD_DIR, f"ITPortalAgent_{digest}.exe")
    if os.path.isfile(output_path):
        return output_path

    # one build at a time; a request that waited here usually finds the finished file
    with AGENT_BUILD_LOCK:
        if os.path.isfile(output_path):
            return output_path
        compile_windows_agent(config_source, output_path)
        prune_agent_builds()
    return output_path


def compile_windows_agent(config_source, output_path):
    csc = find_csc()
    if not csc:
        raise HTTPException(status_code=503, detail=(
            "The Windows installer can't be built on this server: the C# compiler (csc.exe from "
            ".NET Framework 4) was not found. Run the backend on Windows, or use the Python agent."))

    with tempfile.TemporaryDirectory() as build_dir:
        config_path = os.path.join(build_dir, "AgentConfig.cs")
        with open(config_path, "w", encoding="utf-8") as config_file:
            config_file.write(config_source)
        temp_output = os.path.join(build_dir, "ITPortalAgent.exe")
        try:
            result = subprocess.run(
                [csc, "/nologo", "/utf8output", "/target:exe", "/optimize+", "/platform:anycpu",
                 f"/out:{temp_output}", AGENT_SOURCE, config_path],
                capture_output=True, encoding="utf-8", errors="replace", timeout=120)
        except subprocess.TimeoutExpired:
            raise HTTPException(status_code=500, detail="Building the Windows installer timed out.")
        if result.returncode != 0 or not os.path.isfile(temp_output):
            compiler_output = (result.stdout + result.stderr).strip()[-2000:]
            raise HTTPException(status_code=500, detail=f"Building the Windows installer failed: {compiler_output}")
        partial = output_path + ".part"
        shutil.copyfile(temp_output, partial)
        os.replace(partial, output_path)


