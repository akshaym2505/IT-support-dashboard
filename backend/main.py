def created_sort_key(value):
    """Tickets store ISO timestamps (new) or JS toLocaleString() text (old)."""
    if value:
        try:
            parsed = datetime.fromisoformat(value)
            return parsed.astimezone(timezone.utc).replace(tzinfo=None) if parsed.tzinfo else parsed
        except ValueError:
            pass
        try:
            return datetime.strptime(value, "%m/%d/%Y, %I:%M:%S %p")
        except ValueError:
            pass
    return datetime.min


def next_ticket_id(conn):
    numbers = []
    for row in conn.execute("SELECT id FROM tickets WHERE id LIKE 'INC-%'"):
        match = re.fullmatch(r"INC-(\d+)", row["id"] or "")
        if match:
            numbers.append(int(match.group(1)))
    return f"INC-{max(numbers, default=1000) + 1}"


def require_choice(value, choices, field):
    normalized = (value or "").strip().lower()
    if normalized not in choices:
        raise HTTPException(status_code=422, detail=f"{field} must be one of: {', '.join(choices)}")
    return normalized


def fetch_ticket(conn, ticket_id):
    row = conn.execute('''SELECT t.*,
                              (SELECT COUNT(*) FROM ticket_notes n WHERE n.ticket_id = t.id) AS notes_count,
                              (SELECT COALESCE(SUM(time_spent_minutes), 0) FROM ticket_notes n
                                 WHERE n.ticket_id = t.id) AS total_time_minutes
                          FROM tickets t WHERE t.id = ?''', (ticket_id,)).fetchone()
    return dict(row) if row else None


def ensure_ticket_exists(conn, ticket_id):
    if not conn.execute("SELECT 1 FROM tickets WHERE id = ?", (ticket_id,)).fetchone():
        raise HTTPException(status_code=404, detail=f"Ticket {ticket_id} not found.")


def fetch_note(conn, ticket_id, note_id):
    row = conn.execute("SELECT * FROM ticket_notes WHERE id = ? AND ticket_id = ?", (note_id, ticket_id)).fetchone()
    return dict(row) if row else None


